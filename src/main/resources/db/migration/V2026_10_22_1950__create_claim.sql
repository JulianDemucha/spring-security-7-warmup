CREATE TABLE claim
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    policy_id      BIGINT                   NOT NULL,
    description    VARCHAR(2000)            NOT NULL,
    incident_date  DATE                     NOT NULL,
    claimed_amount NUMERIC(12, 2)           NOT NULL,
    status         VARCHAR(20)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT                   NOT NULL,
    CONSTRAINT pk_claim PRIMARY KEY (id),
    CONSTRAINT fk_claim_policy FOREIGN KEY (policy_id) REFERENCES policy (id),
    CONSTRAINT ck_claim_amount CHECK (claimed_amount > 0),
    CONSTRAINT ck_claim_status CHECK (status IN ('NEW', 'IN_REVIEW', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_claim_policy_id ON claim (policy_id);