CREATE TABLE policy
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    policy_number VARCHAR(30)         NOT NULL,
    start_date    DATE           NOT NULL,
    end_date      DATE           NOT NULL,
    sum_insured   NUMERIC(12, 2) NOT NULL,
    customer_id   BIGINT         NOT NULL,
    CONSTRAINT pk_policy PRIMARY KEY (id),
    CONSTRAINT uq_policy_policy_number UNIQUE (policy_number),
    CONSTRAINT fk_policy_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT ck_policy_dates CHECK (end_date > start_date),
    CONSTRAINT ck_policy_sum CHECK (sum_insured > 0)
);

CREATE INDEX idx_policy_customer_id ON policy (customer_id);